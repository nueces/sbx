import json
from pathlib import Path

import pytest

from sbx import gateway
from sbx.runtime import ConfigError

FIXTURES = json.loads(
    (Path(__file__).parents[1] / "gateway/testdata/worker-config-cases.json").read_text()
)


def _parse(network: dict) -> gateway.GatewayConfig:
    parsed = gateway.parse_config({"network": network}, platform="linux")
    assert parsed is not None
    return parsed


@pytest.mark.parametrize("case", FIXTURES, ids=[case["name"] for case in FIXTURES])
def test_worker_config_matches_cross_language_fixture(case: dict) -> None:
    # Deny fixtures were generated by the pre-allow baseline: deny digests must not change.
    config = _parse(case["network"])
    assert config.default == case["mode"]
    assert config.worker_config("vm-fixture", "generation-1") == case["worker"]
    assert config.digest("vm-fixture", "generation-1") == case["canonical_digest"]


def test_allow_keeps_explicit_credential_restrictions() -> None:
    with pytest.raises(ConfigError, match="DNS hostnames"):
        _parse(
            {
                "default": "allow",
                "policy": [
                    {
                        "id": "api",
                        "mode": "http-mediated",
                        "hosts": ["93.184.216.34"],
                        "ports": [443],
                    }
                ],
                "credential": [
                    {
                        "id": "token",
                        "environment": "API_TOKEN",
                        "method": "command",
                        "options": {"argv": ["get-token"]},
                        "bindings": [
                            {"policies": ["api"], "header": "Authorization: Bearer {placeholder}"}
                        ],
                    }
                ],
            }
        )
